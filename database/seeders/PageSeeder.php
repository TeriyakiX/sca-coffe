     * Раздел 25 документа: страницы убираются с сайта.
     * Не удаляем строки, а переводим в архив — данные остаются, публикация прекращается.
     */
    private function legacySlugs(): array
    {
        return (array) config('legacy_pages.gone');
    }

    public final function run(): void
    {
        foreach ($this->items() as $index => $item) {
            $this->upsertRecord(
                Page::class,
                [Page::SLUG => $item[Page::SLUG]],
                $item + [
                    Page::STATUS => PublicationStatusEnum::PUBLISHED->value,
                    Page::SORT_ORDER => ($index + 1) * 10,
                ],
            );
        }

        // Закрытые страницы и те, чьи адреса теперь ведут редиректом,
        // из публикации убираем: иначе в списке «Сведений» возникает цепочка переходов
        $archived = array_merge(
            $this->legacySlugs(),
            array_keys((array) config('legacy_pages.redirects')),
        );

        Page::query()
            ->whereIn(Page::SLUG, $archived)
            ->update([Page::STATUS => PublicationStatusEnum::ARCHIVED->value]);
    }

