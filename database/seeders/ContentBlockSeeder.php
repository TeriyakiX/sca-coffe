        foreach ($this->blocks() as $block) {
            $sort += 10;

            $this->upsertRecord(
                ContentBlock::class,
                [ContentBlock::KEY => $block[ContentBlock::KEY]],
                $block + [ContentBlock::SORT_ORDER => $sort],
            );
        }
    }

